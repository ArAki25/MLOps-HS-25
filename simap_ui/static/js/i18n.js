function applyLang(lang) {
    var t = TRANSLATIONS[lang] || TRANSLATIONS['de'];
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        if (t[key] !== undefined) el.textContent = t[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
        var key = el.getAttribute('data-i18n-placeholder');
        if (t[key] !== undefined) el.placeholder = t[key];
    });
    var cur = document.getElementById('lang-current');
    if (cur) cur.textContent = lang.toUpperCase();
    document.querySelectorAll('.lang-option').forEach(function(btn) {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
    document.documentElement.lang = lang;
    localStorage.setItem('sajf-lang', lang);
}

function setLang(lang) {
    applyLang(lang);
    var menu = document.getElementById('lang-menu');
    if (menu) menu.classList.remove('open');
}

function toggleLangMenu(evt) {
    if (evt) evt.stopPropagation();
    document.getElementById('lang-menu').classList.toggle('open');
}

document.addEventListener('click', function(e) {
    var m = document.getElementById('lang-menu');
    if (m && !m.contains(e.target)) m.classList.remove('open');
});

(function() {
    var saved = localStorage.getItem('sajf-lang') || 'de';
    applyLang(saved);
})();
